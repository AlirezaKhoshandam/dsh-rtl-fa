/**
 * Build the DSH client bundle and copy the small Host half.
 *
 * DSH serves `dsh.client` as one CommonJS-style factory registered with
 * `window.__ModuleLoader__`. esbuild bundles our ESM source into that factory;
 * React stays external because it belongs to the shell's shared module table.
 *
 * The native esbuild executable is spawned with inherited stdio instead of the
 * JS API: the JS API starts a piped service process, which some constrained
 * Windows sandboxes deny. The CLI needs no pipe and works in both worlds.
 */
import { spawnSync } from 'node:child_process'
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(new URL('.', import.meta.url)))
const packageJson = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
const outFile = join(root, 'lib', 'client.js')
const tempFile = join(root, '.build', 'client.cjs')

await mkdir(join(root, 'lib'), { recursive: true })
await mkdir(join(root, '.build'), { recursive: true })

const executable = join(
  root,
  'node_modules',
  '@esbuild',
  `${process.platform}-${process.arch}`,
  process.platform === 'win32' ? 'esbuild.exe' : join('bin', 'esbuild'),
)
const args = [
  'src/client/index.js',
  '--bundle',
  '--format=cjs',
  '--platform=browser',
  '--target=chrome120',
  '--external:react',
  '--external:react/jsx-runtime',
  '--loader:.css=text',
  '--legal-comments=none',
  `--outfile=${tempFile}`,
]
const build = spawnSync(executable, args, { cwd: root, stdio: 'inherit' })
if (build.error) throw build.error
if (build.status !== 0) throw new Error(`esbuild exited with status ${String(build.status)}`)

const bundle = (await readFile(tempFile, 'utf8')).trimEnd()
const banner = `/**
 * ${packageJson.name} v${packageJson.version} — generated by scripts/build.mjs.
 * Source: src/client/. Do not edit this file directly.
 */
`
const wrapper = `${banner}window.__ModuleLoader__.load({
  id: ${JSON.stringify(packageJson.name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${indent(bundle, 4)}
    return module.exports;
  }
});
`

await writeFile(outFile, wrapper, 'utf8')
await copyFile(join(root, 'src', 'index.js'), join(root, 'lib', 'index.js'))
await rm(tempFile, { force: true })

console.log(`built ${outFile} (${Buffer.byteLength(wrapper)} bytes)`)

/**
 * Indent a generated bundle inside the module factory without changing its
 * semantics. Blank lines stay blank.
 *
 * @param {string} source - generated CJS code.
 * @param {number} spaces - indentation width.
 * @returns {string}
 */
function indent(source, spaces) {
  const pad = ' '.repeat(spaces)
  return source.split('\n').map((line) => (line === '' ? '' : `${pad}${line}`)).join('\n')
}
